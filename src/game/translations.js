export function translateLog(text, lang) {
  if (lang !== 'bg') return text;
  let res = text;
  
  // Replace names
  res = res.replace(/Player A/g, 'Играч А');
  res = res.replace(/Player B/g, 'Играч Б');
  res = res.replace(/Computer \(AI\)/g, 'Компютър (AI)');
  res = res.replace(/Player 1 \(A\)/g, 'Играч 1 (А)');
  res = res.replace(/Player 2 \(B\)/g, 'Играч 2 (Б)');
  
  // Replace suits
  res = res.replace(/\bSPADES\b/gi, 'ПИКА');
  res = res.replace(/\bHEARTS\b/gi, 'КУПА');
  res = res.replace(/\bDIAMONDS\b/gi, 'КАРО');
  res = res.replace(/\bCLUBS\b/gi, 'СПАТИЯ');
  
  // Replace specific phrases
  res = res.replace(/searches deck and draws an Elite card/g, 'търси в тестето и тегли Елитна карта');
  res = res.replace(/searches DEFEATED pile and draws an Elite card/g, 'търси в купата с победени и тегли Елитна карта');
  res = res.replace(/taking (\d+) fatigue damage/g, 'получавайки $1 щети от умора');
  res = res.replace(/died to fatigue damage/g, 'умря от щети от умора');
  res = res.replace(/Game Over/gi, 'Край на играта');
  
  res = res.replace(/Plays Elite Card/g, 'изиграва Елитна карта');
  res = res.replace(/Plays Normal Card/g, 'изиграва Нормална карта');
  res = res.replace(/Plays/g, 'изиграва');
  res = res.replace(/draws/g, 'изтегля');
  res = res.replace(/from DEFEATED pile/g, 'от купата с ПОБЕДЕНИ');
  
  res = res.replace(/becomes a Tank and STUNS all enemy board cards for (\d+) turns!/g, 'става Танк и ЗАШЕМЕТЯВА всички вражески карти на борда за $1 хода!');
  res = res.replace(/becomes a Tank!/g, 'става Танк!');
  res = res.replace(/activates Bulwark! \(Becomes a Tank\)/g, 'активира Bulwark! (Става Танк)');
  res = res.replace(/activates Knock out on enemy/g, 'активира Knock out върху вражеския');
  res = res.replace(/for 1 turn!/g, 'за 1 ход!');
  res = res.replace(/stuns enemy/g, 'зашеметява вражеския');
  
  res = res.replace(/attacks/g, 'атакува');
  res = res.replace(/directly for (\d+) damage/g, 'директно за $1 щети');
  res = res.replace(/damage dealt directly to defending player's LP/g, 'щети, нанесени директно на LP на защитаващия се играч');
  res = res.replace(/Excess damage:/g, 'Излишни щети:');
  
  res = res.replace(/is defeated!/g, 'е победен!');
  res = res.replace(/Defender/g, 'Защитникът');
  res = res.replace(/Attacker/g, 'Атакуващият');
  
  res = res.replace(/gains protective shield bubble/g, 'получава предпазен щит');
  res = res.replace(/gains Berserk \(Haste\/Charge\)/g, 'получава Berserk (Haste/Charge)');
  res = res.replace(/healed LP for (\d+)/g, 'излекува LP за $1');
  res = res.replace(/healed for (\d+)/g, 'се излекува за $1');
  res = res.replace(/LP capped at (\d+)/g, 'LP лимитирано до $1');
  res = res.replace(/LP capped at 150/g, 'LP лимитирано до 150');
  res = res.replace(/Excess/g, 'Излишни');
  res = res.replace(/damage dealt to opponent's LP/g, 'щети нанесени на LP на опонента');
  
  res = res.replace(/Shield pops! Absorbed all/g, 'Щитът се пука! Абсорбира всички');
  res = res.replace(/damage/g, 'щети');
  res = res.replace(/absorbs/g, 'абсорбира');
  res = res.replace(/and does not pop/g, 'и не се пука');
  
  res = res.replace(/BOARD WIPE! All board cards sent to Defeated Piles/g, 'ИЗЧИСТВАНЕ НА БОРДА! Всички карти на борда са изпратени в купите с победени');
  res = res.replace(/Both players' health is increased by 50 LP!/g, 'Здравето на двамата играчи е увеличено с 50 LP!');
  res = res.replace(/Both players draw 4 cards!/g, 'Двамата играчи теглят 4 карти!');
  res = res.replace(/Both players restore 50 LP!/g, 'Двамата играчи възстановяват 50 LP!');
  
  res = res.replace(/Summons defeated Clubs:/g, 'Призовава победени Спатии:');
  res = res.replace(/to board/g, 'на борда');
  res = res.replace(/has fallen!/g, 'падна!');
  
  // Connective words
  res = res.replace(/\bof\b/g, 'на');
  
  return res;
}
